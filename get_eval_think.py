import os
import json
import pandas as pd
import sys

filename = sys.argv[1]
# 1. 自动定位输入文件
input_file = f"{filename}"
if not os.path.exists(input_file):
    # Try alternate location
    if os.path.exists(f"SF110/{filename}.json"):
        input_file = f"SF110/{filename}.json"
    else:
        # Fallback to absolute path or assume relative to script execution
        input_file = f"/home/ubuntu/myren/SF110/{filename}.json"

if not os.path.exists(input_file):
    print(f"Error: {input_file} not found")
    exit(1)

#打开json文件
with open(input_file, "r", encoding='utf-8') as file:
    data = json.load(file)

#确定数据集数量和格式
train_data = []
test_data = []
print("data的长度为：", len(data))

# 2. 统一 Input Template (去掉多余的换行和格式，与 self_rl_data.py 对齐)
input_template = """
# Focal Method
```java
{focal_method}
```

# Test Prefix
```java
{prefix}
```
"""

# 3. 统一 System Prompt (与 self_rl_data.py 完全一致)
# 注意：原 split_dataset.py 中的 prompt 包含了很多示例（few-shot），
# 但 self_rl_data.py 中只使用了 zero-shot 的指令。
# 为了评估的一致性，通常应保持一致。如果 self_rl_data.py 用于 RL 是 zero-shot，那评估也应该是 zero-shot。
# 这里我们用 self_rl_data.py 的版本。
# 
prompt = '''
You are a Java Mutation Testing Assertion Expert, specialized in generating assertions that **precisely detect code defects**.

【Core Task】
Generate an assertion for the given Java method and test context.
1. Must compile (syntactically correct)
2. Must pass in the original correct version
3. Must fail in at least one defective mutant
4. Try to kill as many mutants as possible

【Thinking Path】
1. **Analyze Focal Method**: Understand the logic, return values, side effects, and boundary conditions. Identify "Mutatable Points" (conditional jumps, arithmetic operations, loop boundaries) where bugs often hide.
2. **Trace Test Context**: Identify the object state and method arguments in `test_prefix`. Locate the call to `focal_method`.
3. **Lock Target**: 
   - If the method returns a value, assert on that value.
   - If the method is void, assert on the side effects (state changes in the object).
4. **Design Strong Assertion**: 
   - Avoid weak assertions like `assertNotNull`. 
   - Use specific values from the `test_prefix` to verify exact outcomes.
   - Example: If `focal_method` adds 1 to input 5, assert `assertEquals(6, result)`, NOT `assertTrue(result > 0)`.
   - Consider edge cases: empty lists, null inputs, zero values.

【Strict Constraints】
1. **Target Precision**: Never assert variables generated by other unrelated methods at the end of `test_prefix`. Only focus on the product of `focal_method`.
2. **API Caution**: Do not fabricate non-existent methods (e.g. `getResult()`) unless you are sure it is part of the standard library.
3. **Format**: Please wrap the assertion statement in a Markdown code block, i.e., ```java ... ```. You may optionally include a `<think>...</think>` block before the code block to reason about the mutation.
4. **Compilability**: Variables must already exist; floating point comparisons need delta; numeric suffixes must be accurate.

【Input Format】
You will receive:
1. focal_method: The original correct Java method, possibly with comments
2. test_prefix: Test context (initialized objects and parameters)

【Output Requirements】
1. Output a compilable JUnit assertion statement wrapped in a Java code block.
2. Prefer assertEquals / assertArrayEquals / assertThrows / assertNotEquals.
3. If asserting floating point, provide delta; if verifying exception, use assertThrows.
4. The assertion should distinguish at least one typical mutation (arithmetic replacement, condition reversal, constant return, off-by-one, missing null handling).
'''

# 4. 去除 input() 阻塞，改为参数化或默认值
# 默认 5000 或者按比例划分
DEFAULT_TRAIN_SIZE = 5000
train_length = DEFAULT_TRAIN_SIZE
# 或者 train_length = int(len(data) * 0.9)

print(f"Using train_length = {train_length}")

# ChatML 格式化函数
def format_chatml(system, user):
    return f"<|im_start|>system\n{system}<|im_end|>\n<|im_start|>user\n{user}<|im_end|>\n<|im_start|>assistant\n"

for i in range(len(data)):
    pre = data[i]['prefix']
    assertion = data[i]['assert']
    code = data[i]['focal_method']
    
    # 保留原逻辑：只包含有变异体的数据
    if len(data[i].get('ast_generates', [])) != 0:
        input_text = input_template.format(focal_method=code, prefix=pre)
        user_content = input_text if input_text else "Please generate the assertion."
        
        # 构造 item
        # 为了与 RL 训练 (verl + code.jinja) 保持完全一致的输入分布
        # RL 训练时的结构是：User Message = [System Prompt] + [Input Template] + [Response:]
        
        # 1. 构造完整的 Prompt 文本 (模拟 Jinja 模板的行为)
        full_user_content = (
            prompt.strip()
            + "\n\n"
            + user_content.strip()
            + " You FIRST think about the reasoning process as an internal monologue and then provide the final answer. The reasoning process MUST BE enclosed within <think> </think> tags. The final answer MUST BE a single line of Java code inside a java code block.\n\nResponse:"
        )
        
        # 2. LLaMA-Factory 评测格式 (messages)
        # 我们不使用 role: system，而是将 system prompt 合并到 user content 中，以复现 RL 训练时的结构
        item = {
            "messages": [
                {"role": "user", "content": full_user_content},
                {"role": "assistant", "content": assertion}
            ],
            "assert": assertion,
            "prefix": pre,
            "focal_method": code,
            "ast_generates": data[i].get('ast_generates', []),
             # 额外的元数据，方便 debug
            "original_system": prompt,
            "original_user": user_content
        }
        
        if i >= int(train_length):
            test_data.append(item)
        else:
            train_data.append(item)

# 确定输出路径
output_dir = os.path.dirname(input_file)
if not output_dir: output_dir = "."

train_out = os.path.join(output_dir, "train_think.json")
test_out = os.path.join(output_dir, "test_think.json")

with open(train_out, 'w', encoding='utf-8') as f:
    json.dump(train_data, f, ensure_ascii=False, indent=4)

with open(test_out, 'w', encoding='utf-8') as f:
    json.dump(test_data, f, ensure_ascii=False, indent=4)
    
print(f"Saved to {train_out} and {test_out}")
